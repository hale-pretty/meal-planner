CREATE TABLE ingredient (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL UNIQUE CHECK (btrim(code) <> ''),
    name VARCHAR(200) NOT NULL CHECK (btrim(name) <> ''),
    form VARCHAR(100) NOT NULL CHECK (btrim(form) <> '')
);

CREATE TABLE ingredient_alias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id BIGINT NOT NULL REFERENCES ingredient(id),
    name VARCHAR(200) NOT NULL CHECK (btrim(name) <> ''),
    CONSTRAINT ingredient_alias_unique UNIQUE (ingredient_id, name)
);

CREATE TABLE retailer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL UNIQUE CHECK (btrim(code) <> ''),
    name VARCHAR(200) NOT NULL CHECK (btrim(name) <> ''),
    website_url VARCHAR(1000) NOT NULL CHECK (website_url LIKE 'https://%')
);

CREATE TABLE product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    retailer_id BIGINT NOT NULL REFERENCES retailer(id),
    name VARCHAR(300) NOT NULL CHECK (btrim(name) <> ''),
    product_url VARCHAR(1000) NOT NULL CHECK (product_url LIKE 'https://%'),
    pack_label VARCHAR(200) NOT NULL CHECK (btrim(pack_label) <> ''),
    pack_quantity NUMERIC(12, 3),
    pack_unit VARCHAR(10),
    verified_on DATE NOT NULL,
    CONSTRAINT product_retailer_url_unique UNIQUE (retailer_id, product_url),
    CONSTRAINT product_pack_valid CHECK (
        (pack_quantity IS NULL AND pack_unit IS NULL)
        OR (pack_quantity IS NOT NULL AND pack_quantity > 0 AND pack_unit IS NOT NULL
            AND pack_unit IN ('G', 'ML', 'EACH'))
    )
);

CREATE TABLE ingredient_product_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id BIGINT NOT NULL REFERENCES ingredient(id),
    product_id BIGINT NOT NULL REFERENCES product(id),
    reviewed_on DATE NOT NULL,
    CONSTRAINT ingredient_product_unique UNIQUE (ingredient_id, product_id)
);

CREATE INDEX product_retailer_idx ON product(retailer_id);
CREATE INDEX ingredient_product_product_idx ON ingredient_product_mapping(product_id);

