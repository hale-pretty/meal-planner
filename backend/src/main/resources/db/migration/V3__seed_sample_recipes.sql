CREATE TABLE recipe (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(100) NOT NULL UNIQUE,
 name VARCHAR(200) NOT NULL,
 description VARCHAR(1000) NOT NULL,
 cuisine VARCHAR(30) NOT NULL CHECK (cuisine IN ('american','irish','vietnamese')),
 meal_type VARCHAR(30) NOT NULL CHECK (meal_type IN ('breakfast','lunch','dinner')),
 servings INTEGER NOT NULL CHECK (servings > 0),
 cooking_time_minutes INTEGER NOT NULL CHECK (cooking_time_minutes > 0),
 vegetarian BOOLEAN NOT NULL,
 vegan BOOLEAN NOT NULL
);
CREATE TABLE recipe_ingredient (
 recipe_id BIGINT NOT NULL REFERENCES recipe(id),
 position INTEGER NOT NULL,
 ingredient_id BIGINT NOT NULL REFERENCES ingredient(id),
 quantity NUMERIC(12,3) NOT NULL CHECK (quantity > 0),
 unit VARCHAR(10) NOT NULL CHECK (unit IN ('G','KG','ML','L','EACH')),
 PRIMARY KEY (recipe_id, position), UNIQUE (recipe_id, ingredient_id)
);
CREATE TABLE recipe_step (
 recipe_id BIGINT NOT NULL REFERENCES recipe(id),
 step_number INTEGER NOT NULL CHECK (step_number > 0),
 instruction VARCHAR(1000) NOT NULL,
 PRIMARY KEY (recipe_id, step_number)
);

